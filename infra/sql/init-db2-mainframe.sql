-- Layer 20: IBM DB2 Sovereign Mainframe RTGS & Orbital Audit Ledger
CREATE TABLE SOVEREIGN_RTGS_VAULT (
    MAINFRAME_SEQ_ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 5000000, INCREMENT BY 1),
    SETTLEMENT_UUID CHAR(36) NOT NULL,
    CENTRAL_BANK_BIC VARCHAR(32) NOT NULL,
    CURRENCY_ISO CHAR(3) NOT NULL,
    AMOUNT_MINOR_UNITS BIGINT NOT NULL,
    ZK_MERKLE_PROOF CHAR(64) NOT NULL,
    ARCHIVED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (MAINFRAME_SEQ_ID)
);

CREATE INDEX IDX_DB2_SETTLEMENT_UUID ON SOVEREIGN_RTGS_VAULT(SETTLEMENT_UUID);
